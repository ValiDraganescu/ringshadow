/// The glyph for `c` (small letters as capitals; anything else a box).
inline const Glyph& glyph(char c) {
    static constexpr Glyph box{'?', {"#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#####"}};
    if (c >= 'a' && c <= 'z') c = static_cast<char>(c - 'a' + 'A');
    for (const Glyph& g : glyphs) if (g.c == c) return g;
    return box;
}

